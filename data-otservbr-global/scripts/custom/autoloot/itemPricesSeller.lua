function Item.getPrice(self)
    local clientId = self:getId()
    local itemData = ItemPrices[clientId]
	
    if not itemData then
        return nil
    end

    -- Verificar si el ítem tiene un requisito de cargas y, si es así, comprobarlo
    if itemData.requiredCharges and self:getCharges() ~= itemData.requiredCharges then
        return nil -- No se venderá si no cumple con el número de cargas requerido
    end

    return itemData.price
end
